-- ============================================================ içerik
create table if not exists courses (
  id text primary key,
  title text not null,
  level text not null default 'A1'
);

create table if not exists units (
  id int primary key,
  course_id text not null default 'a1' references courses on delete cascade,
  position int not null,
  title_tr text not null,
  title_en text not null default ''
);

create table if not exists lessons (
  id int primary key,
  unit_id int not null references units on delete cascade,
  position int not null,
  title_tr text not null,
  title_en text not null default '',
  summary_tr text not null default '',
  content jsonb not null default '{}', -- { learn: LearnBlock[], listen: {en,tr}[] }
  published boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists books (
  id text primary key,
  title text not null,
  title_tr text not null default '',
  author text not null default '',
  year int,
  category text not null default '',
  description_tr text not null default '',
  cover jsonb not null default '{}',
  chapters_planned int not null default 12,
  position int not null default 99,
  published boolean not null default false
);

create table if not exists chapters (
  id text primary key, -- "<kitap>-NN"
  book_id text not null references books on delete cascade,
  number int not null,
  title_en text not null,
  title_tr text not null default '',
  word_count int not null default 0,
  published boolean not null default false,
  unique (book_id, number)
);

create table if not exists sentences (
  id bigint generated by default as identity primary key,
  chapter_id text not null references chapters on delete cascade,
  position int not null,
  text_en text not null,
  paragraph boolean not null default false,
  unique (chapter_id, position)
);

create table if not exists vocabulary (
  id bigint generated by default as identity primary key,
  lemma text not null unique,
  pos text not null default '',
  meaning_tr text not null,
  ipa text,
  example_en text,
  example_tr text,
  level text not null default 'A1',
  source text,       -- "lesson:3" | "chapter:oz-01"
  source_label text
);

create table if not exists tokens (
  id bigint generated by default as identity primary key,
  sentence_id bigint not null references sentences on delete cascade,
  position int not null,
  surface text not null,
  lemma text not null,
  vocabulary_id bigint references vocabulary on delete set null,
  unique (sentence_id, position)
);

-- Cümle çevirisi (sentence_id) veya kelimenin bağlamsal anlamı (token_id)
create table if not exists translations (
  id bigint generated by default as identity primary key,
  sentence_id bigint references sentences on delete cascade,
  token_id bigint references tokens on delete cascade,
  lang text not null default 'tr',
  text text not null,
  check ((sentence_id is null) <> (token_id is null))
);
create index if not exists translations_sentence_idx on translations (sentence_id);
create index if not exists translations_token_idx on translations (token_id);

create table if not exists questions (
  id bigint generated by default as identity primary key,
  lesson_id int references lessons on delete cascade,
  unit_id int references units on delete cascade,
  chapter_id text references chapters on delete cascade,
  section text not null check (section in ('practice', 'test', 'unit', 'chapter', 'final')),
  position int not null,
  type text not null check (type in ('mcq', 'fill', 'order', 'match', 'listen')),
  data jsonb not null
);
create index if not exists questions_lesson_idx on questions (lesson_id);
create index if not exists questions_chapter_idx on questions (chapter_id);
create index if not exists sentences_chapter_idx on sentences (chapter_id);
create index if not exists tokens_sentence_idx on tokens (sentence_id);

-- ============================================================ kullanıcı
create table if not exists profiles (
  id uuid primary key references auth.users on delete cascade,
  display_name text,
  role text not null default 'user' check (role in ('user', 'admin')),
  prefs jsonb not null default '{}',
  created_at timestamptz not null default now()
);

create or replace function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, display_name) values (new.id, split_part(new.email, '@', 1))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function handle_new_user();

create table if not exists user_progress (
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  kind text not null check (kind in ('lesson', 'chapter', 'test')),
  ref text not null,
  status text not null check (status in ('started', 'completed')),
  score int,
  position int,
  updated_at timestamptz not null default now(),
  primary key (user_id, kind, ref)
);

create table if not exists user_words (
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  lemma text not null,
  meaning_tr text not null,
  example_en text,
  example_tr text,
  source_label text,
  status text not null default 'learning' check (status in ('learning', 'known')),
  box int not null default 1 check (box between 1 and 5),
  due_at timestamptz not null default now(),
  correct int not null default 0,
  wrong int not null default 0,
  created_at timestamptz not null default now(),
  primary key (user_id, lemma)
);

create table if not exists test_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  ref text not null, -- "lesson-3" | "unit-1" | "chapter-oz-01"
  score int not null,
  passed boolean not null,
  wrong int[] not null default '{}',
  created_at timestamptz not null default now()
);
create index if not exists test_attempts_user_idx on test_attempts (user_id, created_at desc);

-- ============================================================ RLS
create or replace function is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

do $$
declare t text;
begin
  foreach t in array array['courses','units','lessons','books','chapters','sentences','vocabulary','tokens','translations','questions'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "%s okuma" on %I', t, t);
    execute format('create policy "%s okuma" on %I for select using (true)', t, t);
    execute format('drop policy if exists "%s admin" on %I', t, t);
    execute format('create policy "%s admin" on %I for all to authenticated using (is_admin()) with check (is_admin())', t, t);
  end loop;
  foreach t in array array['user_progress','user_words','test_attempts'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "%s sahibi" on %I', t, t);
    execute format('create policy "%s sahibi" on %I for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid())', t, t);
  end loop;
end $$;

alter table profiles enable row level security;
drop policy if exists "profil okuma" on profiles;
create policy "profil okuma" on profiles for select to authenticated using (id = auth.uid() or is_admin());
drop policy if exists "profil güncelleme" on profiles;
create policy "profil güncelleme" on profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
-- Kullanıcı kendi rolünü değiştiremez: yalnızca bu sütunlar güncellenebilir.
revoke update on profiles from authenticated;
grant update (display_name, prefs) on profiles to authenticated;

